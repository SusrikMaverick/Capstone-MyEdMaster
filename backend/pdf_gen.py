import re
import textwrap

from fpdf import FPDF

ACCENT = (79, 110, 247)
DARK = (26, 31, 54)
BODY_COLOR = (40, 40, 55)
MUTED = (130, 130, 150)

MAX_FILL_LEN = 40


def _sanitize(text):
    """Replace common unicode chars with ASCII, then drop anything else outside latin-1."""
    replacements = {
        "\u2018": "'", "\u2019": "'",
        "\u201c": '"', "\u201d": '"',
        "\u2010": "-", "\u2011": "-", "\u2012": "-",
        "\u2013": "-", "\u2014": "--",
        "\u2026": "...", "\u00a0": " ",
        "\u2022": "*", "\u25cf": "*",
        "\u00b7": "*", "\u2023": ">",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    # Shorten long blank-fill runs so they don't overflow the page
    text = re.sub(r"_{5,}", "_" * MAX_FILL_LEN, text)
    return text.encode("latin-1", errors="replace").decode("latin-1")


def _safe_multi_cell(pdf, w, h, text, **kwargs):
    """Write text, resetting X to left margin first to avoid drift."""
    pdf.set_x(pdf.l_margin)
    pdf.multi_cell(w, h, text, **kwargs)


def create_pdf(title, body):
    title = _sanitize(title)
    body = _sanitize(body)

    pdf = FPDF()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=25)

    usable_w = pdf.w - pdf.l_margin - pdf.r_margin

    # Branding header
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(*ACCENT)
    pdf.cell(usable_w, 8, "MyEdMaster", new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(*ACCENT)
    pdf.set_line_width(0.5)
    y = pdf.get_y()
    pdf.line(pdf.l_margin, y, pdf.w - pdf.r_margin, y)
    pdf.ln(10)

    # Title
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(*DARK)
    _safe_multi_cell(pdf, usable_w, 10, title, align="C")
    pdf.ln(8)

    # Body
    pdf.set_text_color(*BODY_COLOR)
    for line in body.split("\n"):
        stripped = line.strip()
        if not stripped:
            pdf.ln(4)
            continue

        is_heading = (
            re.match(r"^\d+\.\s+[A-Z]", stripped)
            or (stripped.isupper() and len(stripped) > 3)
        )
        if is_heading:
            pdf.ln(3)
            pdf.set_font("Helvetica", "B", 12)
            _safe_multi_cell(pdf, usable_w, 7, stripped)
            pdf.ln(2)
        else:
            pdf.set_font("Helvetica", "", 11)
            _safe_multi_cell(pdf, usable_w, 6, stripped)

    # Footer
    pdf.ln(12)
    pdf.set_draw_color(200, 200, 210)
    pdf.set_line_width(0.3)
    y = pdf.get_y()
    pdf.line(pdf.l_margin, y, pdf.w - pdf.r_margin, y)
    pdf.ln(5)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(*MUTED)
    pdf.cell(usable_w, 5, "Generated by MyEdMaster Legal Chatbot", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(usable_w, 5, "This document is for informational purposes only and does not constitute legal advice.", align="C")

    return bytes(pdf.output())
